// Report generator — console + markdown output for evaluation results.

import type { EvalReport, EventType, SystemMetrics } from './types'

function bar(fraction: number, width = 20): string {
  const filled = Math.round(fraction * width)
  const empty = width - filled
  return '\u2588'.repeat(filled) + '\u2591'.repeat(empty)
}

function pct(n: number): string {
  return `${(n * 100).toFixed(0)}%`
}

function pad(s: string, len: number): string {
  return s.padEnd(len)
}

const EVENT_TYPE_LABELS: Record<EventType, string> = {
  rate_decision: 'Rate Decisions',
  cpi_surprise: 'CPI Surprises',
  oil_shock: 'Oil/Commodity',
  banking_stress: 'Banking Stress',
  geopolitical: 'Geopolitical',
  currency_fx: 'Currency/FX',
}

// ── Console Report ─────────────────────────────────────────

export function generateConsoleReport(report: EvalReport): string {
  const lines: string[] = []
  const sep = '\u2550'.repeat(50)

  lines.push(sep)
  lines.push(`PRISM EVALUATION REPORT \u2014 ${report.eventCount} Historical Events`)
  lines.push(`Generated: ${report.timestamp}`)
  lines.push(sep)
  lines.push('')

  // Directional Accuracy
  lines.push('DIRECTIONAL ACCURACY')
  lines.push(`  Single-agent:  ${pad(pct(report.singleAgent.directionalAccuracy), 5)} ${bar(report.singleAgent.directionalAccuracy)}`)
  lines.push(`  Multi-agent:   ${pad(pct(report.multiAgent.directionalAccuracy), 5)} ${bar(report.multiAgent.directionalAccuracy)}`)
  lines.push('')

  // Range Coverage
  lines.push('CONFIDENCE RANGE COVERAGE')
  lines.push(`  Single-agent:  ${pad(pct(report.singleAgent.rangeCoverage), 5)} ${bar(report.singleAgent.rangeCoverage)}`)
  lines.push(`  Multi-agent:   ${pad(pct(report.multiAgent.rangeCoverage), 5)} ${bar(report.multiAgent.rangeCoverage)}`)
  lines.push('')

  // Evidence Grounding
  lines.push('EVIDENCE GROUNDING')
  lines.push(`  Multi-agent:   ${pad(pct(report.multiAgent.evidenceGrounding), 5)} ${bar(report.multiAgent.evidenceGrounding)}`)
  lines.push('')

  // Per Event Type
  lines.push('BY EVENT TYPE (Multi-Agent)')
  for (const [type, label] of Object.entries(EVENT_TYPE_LABELS)) {
    const metrics = report.multiAgent.perEventType.get(type as EventType)
    if (metrics) {
      lines.push(`  ${pad(label + ':', 20)} ${pad(pct(metrics.accuracy), 5)} accuracy, ${pct(metrics.coverage)} coverage`)
    }
  }
  lines.push('')
  lines.push(sep)

  return lines.join('\n')
}

// ── Markdown Report ────────────────────────────────────────

export function generateMarkdownReport(report: EvalReport): string {
  const lines: string[] = []

  lines.push('# Prism Evaluation Report')
  lines.push('')
  lines.push(`**Events:** ${report.eventCount} | **Generated:** ${report.timestamp}`)
  lines.push('')

  // Summary Table
  lines.push('## Summary')
  lines.push('')
  lines.push('| Metric | Single-Agent | Multi-Agent | Delta |')
  lines.push('|--------|-------------|-------------|-------|')

  const dAcc = report.multiAgent.directionalAccuracy - report.singleAgent.directionalAccuracy
  const dCov = report.multiAgent.rangeCoverage - report.singleAgent.rangeCoverage
  lines.push(`| Directional Accuracy | ${pct(report.singleAgent.directionalAccuracy)} | ${pct(report.multiAgent.directionalAccuracy)} | +${pct(dAcc)} |`)
  lines.push(`| Range Coverage | ${pct(report.singleAgent.rangeCoverage)} | ${pct(report.multiAgent.rangeCoverage)} | +${pct(dCov)} |`)
  lines.push(`| Evidence Grounding | N/A | ${pct(report.multiAgent.evidenceGrounding)} | — |`)
  lines.push('')

  // Per Event Type
  lines.push('## By Event Type')
  lines.push('')
  lines.push('| Event Type | Multi-Agent Accuracy | Multi-Agent Coverage | Single-Agent Accuracy |')
  lines.push('|------------|---------------------|---------------------|----------------------|')

  for (const [type, label] of Object.entries(EVENT_TYPE_LABELS)) {
    const ma = report.multiAgent.perEventType.get(type as EventType)
    const sa = report.singleAgent.perEventType.get(type as EventType)
    if (ma && sa) {
      lines.push(`| ${label} | ${pct(ma.accuracy)} | ${pct(ma.coverage)} | ${pct(sa.accuracy)} |`)
    }
  }

  lines.push('')

  // Per-Event Detail
  lines.push('## Per-Event Results')
  lines.push('')
  lines.push('| Event | Type | Multi-Agent Dir | Single-Agent Dir | Actual Dir |')
  lines.push('|-------|------|----------------|-----------------|------------|')

  for (const result of report.results) {
    lines.push(`| ${result.eventId} | ${result.eventType} | ${result.multiAgent.direction} | ${result.singleAgent.direction} | ${result.actual.netDirection} |`)
  }

  lines.push('')
  lines.push('---')
  lines.push('*Generated by Prism Evaluation Harness*')

  return lines.join('\n')
}
